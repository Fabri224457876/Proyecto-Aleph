const PREFIXES: Array<[string, string]> = [
  ["case.", "Caso"],
  ["entity.", "Entidad"],
  ["relation.", "Relación"],
  ["source.", "Fuente"],
  ["finding.", "Hallazgo"],
  ["menard.", "MENARD"],
  ["funes.", "FUNES"],
  ["attack.", "ATT&CK"],
  ["collect.", "Recolección"],
];

export function auditActionLabel(code: string): string {
  if (LABELS[code]) return LABELS[code];
  const prefix = PREFIXES.find(([p]) => code.startsWith(p));
  return prefix ? `${prefix[1]}: ${code.slice(prefix[0].length).replace(/[._]/g, " ")}` : code;
}
